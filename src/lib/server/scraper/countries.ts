export interface ShipTo {
  /** ISO 3166-1 alpha-2, or 'unknown' for a name Discogs lists that has no current code. */
  code: string;
  name: string;
}

/** Maps a Discogs country name to its ISO code; unknown names keep the name and get 'unknown'. */
export function countryCode(name: string): ShipTo {
  const trimmed = name.trim();
  const direct = DISCOGS_COUNTRY_CODES[trimmed];
  if (direct) return { code: direct, name: trimmed };
  const lower = trimmed.toLowerCase();
  for (const [key, code] of Object.entries(DISCOGS_COUNTRY_CODES)) {
    if (key.toLowerCase() === lower) return { code, name: trimmed };
  }
  return { code: 'unknown', name: trimmed };
}
